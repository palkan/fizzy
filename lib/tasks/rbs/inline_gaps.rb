require "prism"
require "rbs"

module Rbs
  # Declares what inline RBS and rbs_rails can't, from the Ruby sources and the booted app, so it can
  # go in a generated signature file:
  #
  # * Namespaces Zeitwerk defines implicitly from directories, such as `Boards` in `class Boards::ColumnsController`.
  # * Mixins of something other than a single constant: `include A, B`, `extend self`, and the route helpers module.
  #   Their call sites are marked with `# @rbs skip` to keep the inline parser from flagging them.
  # * `ClassMethods` of concerns, which ActiveSupport::Concern extends the including class with.
  # * Methods Rails macros define: `delegate`, `alias_method`, `store`/`store_accessor`, `serialize`, `attribute`,
  #   `class_attribute`, and `cattr_*`/`mattr_*`/`thread_mattr_*`. A trailing `#: Type` on the macro types them,
  #   as with `attr_reader`; otherwise they're untyped.
  # * Scopes declared in model concerns (rbs_rails only reads the model's own file) and `has_rich_text` attributes.
  # * Model class methods on relations, which delegate to the model, including those inherited by STI subclasses.
  # * Instance methods of current attributes, which ActiveSupport::CurrentAttributes exposes as class methods.
  # * Overloads of macros whose lambdas Rails runs with `instance_exec`, such as `belongs_to ..., default: -> { ... }`,
  #   so the lambdas are typed in the context of an instance.
  # * Mailer actions, which Action Mailer exposes as class methods returning a message to deliver.
  # * Helpers in app/helpers, controller methods exposed with `helper_method`, and route helpers in views.
  #
  # Methods it copies to another class (relations, mailers, views) keep the types annotated inline.
  class InlineGaps
    Definition = Struct.new(:member, :nesting, :visibility)

    MIXIN_METHODS = %i[ include extend prepend ]
    PATH_HELPERS = "Rails.application.routes.url_helpers"
    VISIBILITY_METHODS = %i[ private protected public ]
    CLASS_ACCESSORS = %i[
      cattr_accessor cattr_reader cattr_writer mattr_accessor mattr_reader mattr_writer
      thread_cattr_accessor thread_cattr_reader thread_cattr_writer thread_mattr_accessor thread_mattr_reader thread_mattr_writer
    ]
    INSTANCE_LAMBDA_MACROS = %i[ belongs_to has_passkeys rate_limit ]
    ATTRIBUTE_TYPES = {
      string: "String", text: "String", integer: "Integer", big_integer: "Integer", float: "Float", decimal: "BigDecimal",
      uuid: "String", boolean: "bool", date: "Date", datetime: "ActiveSupport::TimeWithZone", time: "ActiveSupport::TimeWithZone"
    }

    def initialize(paths)
      @signatures = Signatures.new
      @declared = Set.new
      @members = Hash.new { |hash, owner| hash[owner] = [] }
      @methods = Hash.new { |hash, owner| hash[owner] = {} }
      @scopes = Hash.new { |hash, owner| hash[owner] = [] }
      @helper_methods = []
      @macros = []

      paths.each { scan_file it }
      @macros.each { |owners, macro| owners.call.each(&macro) }

      add_class_methods_extensions
      add_model_scopes
      add_rich_text_attributes
      add_relation_class_methods
      add_current_attributes_class_methods
      add_mailer_actions
      add_view_helpers paths.grep(%r{/app/helpers/})
    end

    def to_rbs
      <<~RBS
        # Generated by `bin/rails rbs:inline` — do not edit.
        #
        # Declarations inline RBS and rbs_rails can't express. See lib/tasks/rbs/inline_gaps.rb.

        #{(namespaces + members).join("\n\n")}
      RBS
    end

    # Signatures declared in sig/ (excluding generated ones) and the RBS collection
    class Signatures
      def initialize
        loader = RBS::EnvironmentLoader.new
        lockfile_path = Rails.root.join("rbs_collection.lock.yaml")
        loader.add_collection RBS::Collection::Config::Lockfile.from_lockfile(lockfile_path: lockfile_path, data: YAML.load_file(lockfile_path))
        Rails.root.glob("sig/*").reject { it.basename.to_s == "generated" }.each { loader.add(path: it) }

        @environment = RBS::Environment.from_loader(loader).resolve_type_names
      end

      def type_name?(name)
        @environment.type_name?(type_name(name))
      end

      def method?(owner, name, singleton:)
        if entry = @environment.module_class_entry(type_name(owner))
          entry.each_decl.any? do |decl|
            decl.members.any? { it.is_a?(RBS::AST::Members::MethodDefinition) && it.name == name.to_sym && it.singleton? == singleton }
          end
        end
      end

      private
        def type_name(name)
          RBS::TypeName.parse(name.start_with?("::") ? name : "::#{name}")
        end
    end

    private
      def scan_file(path)
        result = Prism.parse_file(path)
        inline = RBS::InlineParser.parse(RBS::Buffer.new(name: path, content: result.source.source), result)

        @inline_members = {}.compare_by_identity
        inline.declarations.grep(RBS::AST::Ruby::Declarations::ClassDecl).each { index_inline_members it }
        inline.declarations.grep(RBS::AST::Ruby::Declarations::ModuleDecl).each { index_inline_members it }
        @comments = result.comments.to_h { [ it.location.start_line, it.location.slice ] }

        scan result.value
      end

      def index_inline_members(declaration)
        declaration.members.each do |member|
          case member
          when RBS::AST::Ruby::Members::DefMember then @inline_members[member.node] = member
          when RBS::AST::Ruby::Declarations::ClassDecl, RBS::AST::Ruby::Declarations::ModuleDecl then index_inline_members member
          end
        end
      end

      def scan(node, nesting = [], visibility = :public)
        statements_of(node).each do |statement|
          case statement
          when Prism::ClassNode, Prism::ModuleNode
            name = statement.constant_path.slice
            @declared << resolve(name, nesting)
            scan statement.body, nesting + [ name ]
          when Prism::DefNode
            add_definition statement, nesting, visibility if nesting.any?
          when Prism::AliasMethodNode
            if nesting.any?
              new_name, old_name = statement.new_name.slice.delete_prefix(":"), statement.old_name.slice.delete_prefix(":")
              add_macro(nesting) { add_alias it, new_name, old_name }
            end
          when Prism::CallNode
            if nesting.any? && statement.receiver.nil?
              visibility = scan_call(statement, nesting, visibility)
            end
          end
        end
      end

      def statements_of(node)
        case node
        when Prism::ProgramNode then node.statements.body
        when Prism::StatementsNode then node.body
        when Prism::BeginNode then statements_of(node.statements)
        when nil then []
        else [ node ]
        end
      end

      # Returns the visibility for the statements that follow the call
      def scan_call(call, nesting, visibility)
        arguments = call.arguments&.arguments || []

        case call.name
        when *VISIBILITY_METHODS
          if arguments.empty?
            return call.name
          else
            arguments.grep(Prism::DefNode).each { add_definition it, nesting, call.name }
          end
        when :private_class_method
          arguments.grep(Prism::DefNode).each { add_definition it, nesting, :private }
        when *MIXIN_METHODS
          if arguments.many? || arguments.any? { it.slice == PATH_HELPERS || it.is_a?(Prism::SelfNode) }
            # `include A, B` puts A ahead of B in the ancestors, like `include B` followed by `include A`
            arguments.reverse_each { add_mixin nesting, call.name, it }
          end
        when :scope
          if arguments.first.is_a?(Prism::SymbolNode)
            @scopes[owner_of(nesting)] << [ arguments.first.unescaped, parameters_of(arguments.second) ]
          end
        when :delegate
          add_macro(nesting) { add_delegated_methods it, arguments }
        when :alias_method
          add_macro(nesting) { add_alias it, *arguments.first(2).map(&:unescaped) } if arguments.first(2).all?(Prism::SymbolNode)
        when :store, :store_accessor
          type = annotated_type(call, nesting)
          add_macro(nesting) { add_store_accessors it, call.name, arguments, type }
        when :serialize
          type = annotated_type(call, nesting)
          add_macro(nesting) { add_serialized_attribute it, arguments, type }
        when :attribute
          type = annotated_type(call, nesting)
          add_macro(nesting) { add_attributes it, arguments, type }
        when :class_attribute
          type = annotated_type(call, nesting)
          add_macro(nesting) { add_class_attributes it, arguments, type }
        when *CLASS_ACCESSORS
          type = annotated_type(call, nesting)
          add_macro(nesting) { add_class_accessors it, call.name, arguments, type }
        when *INSTANCE_LAMBDA_MACROS
          keys = options_of(arguments).select { |_, value| value.is_a?(Prism::LambdaNode) }.keys
          add_macro(nesting) { add_instance_lambda_overload it, call.name, keys } if keys.any?
        when :helper_method
          names = arguments.grep(Prism::SymbolNode).map(&:unescaped)
          @helper_methods << [ owner_of(nesting), names ]
        when :included, :prepended
          # These blocks run in the including class, which gets the methods their macros define
          @in_included, in_included = true, @in_included
          scan call.block.body, nesting, visibility if call.block.is_a?(Prism::BlockNode)
          @in_included = in_included
        else
          # Like the inline parser, treat calls within other blocks as the module's own
          scan call.block.body, nesting, visibility if call.block.is_a?(Prism::BlockNode)
        end

        visibility
      end

      def owner_of(nesting)
        resolve(nesting.last, nesting[0...-1])
      end

      # Runs once all files are scanned, for the classes the macro applies to: the class it's called in,
      # or the classes that include the concern whose `included` block calls it
      def add_macro(nesting, &macro)
        owner, in_included = owner_of(nesting), @in_included

        owners = -> do
          if in_included && !owner.is_a?(Class)
            @declared.grep(Class).select { it.include?(owner) && !it.superclass.include?(owner) }.sort_by(&:name)
          else
            [ owner ]
          end
        end

        @macros << [ owners, macro ]
      end

      def add_definition(node, nesting, visibility)
        if member = @inline_members[node]
          @methods[owner_of(nesting)][[ member.name, member.singleton? ]] = Definition.new(member, nesting, visibility)
        end
      end

      def add_mixin(nesting, method, argument)
        owner = owner_of(nesting)

        if argument.slice == PATH_HELPERS
          add owner, "#{method} ::_RbsRailsPathHelpers"
        elsif argument.is_a?(Prism::SelfNode)
          add owner, "#{method} ::#{owner.name}"
        elsif argument.is_a?(Prism::ConstantReadNode) || argument.is_a?(Prism::ConstantPathNode)
          add owner, "#{method} ::#{resolve(argument.slice, nesting).name}"
        end
      end

      # The scope's lambda parameters, as RBS method parameters
      def parameters_of(node)
        if node.is_a?(Prism::LambdaNode)
          parameters = node.parameters&.parameters

          [
            *parameters&.requireds&.map { "untyped #{it.name}" },
            *parameters&.optionals&.map { "?untyped #{it.name}" },
            *("*untyped" if parameters&.rest),
            *parameters&.keywords&.map { "#{"?" if it.is_a?(Prism::OptionalKeywordParameterNode)}#{it.name}: untyped" },
            *("**untyped" if parameters&.keyword_rest)
          ].join(", ").then { "(#{it})" }
        else
          "(?)"
        end
      end

      def add_delegated_methods(owner, arguments)
        options = options_of(arguments)

        if target = options[:to]
          prefix = case options[:prefix]
          when Prism::TrueNode then "#{target.slice.delete_prefix(":").delete_prefix("@")}_"
          when Prism::SymbolNode, Prism::StringNode then "#{options[:prefix].unescaped}_"
          end

          arguments.grep(Prism::SymbolNode).each do |method|
            add_method owner, "#{prefix}#{method.unescaped}", "(?) -> untyped"
          end
        end
      end

      def add_alias(owner, new_name, old_name)
        add owner, "alias #{new_name} #{old_name}" unless defined_method?(owner, new_name, singleton: false)
      end

      # `store :column, accessors: [ ... ]` and `store_accessor :column, :key, ...`
      def add_store_accessors(owner, macro, arguments, type)
        options = options_of(arguments)
        names = macro == :store ? Array(options[:accessors]&.then { it.elements if it.is_a?(Prism::ArrayNode) }) : arguments.drop(1)
        type ||= "untyped"

        if macro == :store
          add_method owner, arguments.first.unescaped, "() -> ::ActiveSupport::HashWithIndifferentAccess[::String, untyped] | ...", force: true
        end

        names.grep(Prism::SymbolNode).each do |name|
          accessor = [ affix(options[:prefix], arguments.first, :prefix), name.unescaped, affix(options[:suffix], arguments.first, :suffix) ].join

          add_method owner, accessor, "() -> #{type}"
          add_method owner, "#{accessor}=", "(#{type}) -> #{type}"
          add_method owner, "#{accessor}_changed?", "() -> bool"
          add_method owner, "#{accessor}_was", "() -> #{type}"
          add_method owner, "saved_change_to_#{accessor}?", "() -> bool"
        end
      end

      def affix(option, store, position)
        case option
        when Prism::TrueNode then position == :prefix ? "#{store.unescaped}_" : "_#{store.unescaped}"
        when Prism::SymbolNode, Prism::StringNode then position == :prefix ? "#{option.unescaped}_" : "_#{option.unescaped}"
        end
      end

      # `serialize :column, type: Array` changes the column's type
      def add_serialized_attribute(owner, arguments, type)
        name, type = arguments.first, type || serialized_type(options_of(arguments)[:type])

        if name.is_a?(Prism::SymbolNode) && type
          add_method owner, name.unescaped, "() -> #{type} | ...", force: true
        end
      end

      def serialized_type(node)
        case node&.slice
        when "Array" then "::Array[untyped]"
        when "Hash" then "::Hash[untyped, untyped]"
        end
      end

      # Active Model and Active Record `attribute :name, :type`, and current attributes' `attribute :a, :b`
      def add_attributes(owner, arguments, annotated_type)
        names = arguments.grep(Prism::SymbolNode)

        if owner.is_a?(Class) && owner < ActiveSupport::CurrentAttributes
          type = annotated_type || "untyped"

          names.each do |name|
            [ true, false ].each do |singleton|
              add_method owner, name.unescaped, "() -> #{type}", singleton: singleton
              add_method owner, "#{name.unescaped}=", "(#{type}) -> #{type}", singleton: singleton
            end
          end
        elsif name = names.first
          attribute_type = names.second&.unescaped&.to_sym
          type = annotated_type || ATTRIBUTE_TYPES[attribute_type]&.then { "::#{it.delete_prefix("::")}?".sub("::bool?", "bool?") } || "untyped"

          add_method owner, name.unescaped, "() -> #{type}"
          add_method owner, "#{name.unescaped}=", "(#{type}) -> #{type}"
        end
      end

      def add_class_attributes(owner, arguments, type)
        options = options_of(arguments)
        type ||= "untyped"

        arguments.grep(Prism::SymbolNode).map(&:unescaped).each do |name|
          add_method owner, name, "() -> #{type}", singleton: true
          add_method owner, "#{name}=", "(#{type}) -> #{type}", singleton: true
          add_method owner, "#{name}?", "() -> bool", singleton: true unless options[:instance_predicate].is_a?(Prism::FalseNode)

          unless options[:instance_reader].is_a?(Prism::FalseNode) || options[:instance_accessor].is_a?(Prism::FalseNode)
            add_method owner, name, "() -> #{type}"
            add_method owner, "#{name}?", "() -> bool" unless options[:instance_predicate].is_a?(Prism::FalseNode)
          end

          unless options[:instance_writer].is_a?(Prism::FalseNode) || options[:instance_accessor].is_a?(Prism::FalseNode)
            add_method owner, "#{name}=", "(#{type}) -> #{type}"
          end
        end
      end

      def add_class_accessors(owner, macro, arguments, type)
        options = options_of(arguments)
        type ||= "untyped"
        reader, writer = !macro.end_with?("_writer"), !macro.end_with?("_reader")
        instance = !options[:instance_accessor].is_a?(Prism::FalseNode)

        arguments.grep(Prism::SymbolNode).map(&:unescaped).each do |name|
          if reader
            add_method owner, name, "() -> #{type}", singleton: true
            add_method owner, name, "() -> #{type}" if instance && !options[:instance_reader].is_a?(Prism::FalseNode)
          end

          if writer
            add_method owner, "#{name}=", "(#{type}) -> #{type}", singleton: true
            add_method owner, "#{name}=", "(#{type}) -> #{type}" if instance && !options[:instance_writer].is_a?(Prism::FalseNode)
          end
        end
      end

      def add_instance_lambda_overload(owner, macro, keys)
        lambdas = keys.sort.map { "?#{it}: ^() [self: ::#{owner.name}] -> untyped" }.join(", ")
        add_method owner, macro, "(*untyped, #{lambdas}, **untyped) ?{ (?) -> untyped } -> untyped | ...", singleton: true, force: true, key: keys.sort
      end

      def options_of(arguments)
        arguments.grep(Prism::KeywordHashNode).flat_map(&:elements).grep(Prism::AssocNode).to_h { [ it.key.slice.delete_suffix(":").delete_prefix(":").to_sym, it.value ] }
      end

      # The type in a trailing `#: Type` comment on the call's last line
      def annotated_type(call, nesting)
        if type = @comments[call.location.end_line]&.then { it[/\A#:\s*(.+)\z/, 1]&.strip }
          absolute_type(RBS::Parser.parse_type(type), nesting).to_s
        end
      end

      def add_class_methods_extensions
        @declared.grep(Class).sort_by(&:name).each do |klass|
          inherited = klass.superclass.singleton_class.ancestors

          klass.ancestors.drop(1).each do |mod|
            next if mod.is_a?(Class) || mod.name.nil? || !mod.const_defined?(:ClassMethods, false)

            class_methods = mod::ClassMethods
            if klass.singleton_class.include?(class_methods) && !inherited.include?(class_methods) &&
                (@declared.include?(class_methods) || @signatures.type_name?(class_methods.name))
              add klass, "extend ::#{class_methods.name}"
            end
          end
        end
      end

      def add_model_scopes
        each_model do |model|
          model.ancestors.reverse_each do |mod|
            @scopes[mod].each { |name, parameters| add_scope model, name, parameters }
          end
        end
      end

      def add_rich_text_attributes
        each_model do |model|
          model.reflect_on_all_associations(:has_one).map(&:name).grep(/\Arich_text_/).each do |association|
            name = association.to_s.delete_prefix("rich_text_")

            add_method model, name, "() -> ::ActionText::RichText"
            add_method model, "#{name}=", "(untyped) -> untyped"
            add_method model, "#{name}?", "() -> bool"
            add_scope model, "with_rich_text_#{name}", "()"
            add_scope model, "with_rich_text_#{name}_and_embeds", "()"
          end
        end
      end

      # Relations delegate to the model's class methods: its own, its concerns' `ClassMethods`, and its STI parent's
      def add_relation_class_methods
        each_model do |model|
          relation_methods = "#{model.name}::GeneratedRelationMethods"
          parent = model.superclass

          if parent != ApplicationRecord && @signatures.type_name?("#{parent.name}::GeneratedRelationMethods")
            add relation_methods, "include ::#{parent.name}::GeneratedRelationMethods"
          end

          model.singleton_class.ancestors.each do |mod|
            if mod.name&.end_with?("::ClassMethods") && @declared.include?(mod) && !parent.singleton_class.include?(mod)
              add relation_methods, "include ::#{mod.name}"
            end
          end

          @methods[model].each do |(name, singleton), definition|
            if singleton && definition.visibility == :public
              add_method relation_methods, name, method_types_of(definition)
            end
          end
        end
      end

      def add_current_attributes_class_methods
        @declared.grep(Class).select { it < ActiveSupport::CurrentAttributes }.each do |current|
          @methods[current].each do |(name, singleton), definition|
            if !singleton && definition.visibility == :public
              add_method current, name, method_types_of(definition), singleton: true
            end
          end
        end
      end

      def add_mailer_actions
        @declared.grep(Class).select { it < ActionMailer::Base }.sort_by(&:name).each do |mailer|
          mailer.public_instance_methods(false).sort.each do |action|
            definition = @methods[mailer][[ action, false ]]
            types = definition ? method_types_of(definition, return_type: "::ActionMailer::MessageDelivery") : "(?) -> ::ActionMailer::MessageDelivery"

            add_method mailer, action, types, singleton: true
          end
        end
      end

      def add_view_helpers(paths)
        root = Rails.root.join("app/helpers")
        helpers = paths.map { Pathname(it).relative_path_from(root).sub_ext("").to_s.camelize.constantize }.sort_by(&:name)

        add ActionView::Base, "include ::_RbsRailsPathHelpers"
        helpers.each { add ActionView::Base, "include ::#{it.name}" }

        @helper_methods.each do |controller, names|
          names.each do |name|
            if definition = @methods[controller][[ name.to_sym, false ]]
              add_method ActionView::Base, name, method_types_of(definition)
            end
          end
        end
      end

      def each_model
        @declared.grep(Class).select { it < ActiveRecord::Base && @signatures.type_name?("#{it.name}::GeneratedRelationMethods") }.sort_by(&:name).each do |model|
          yield model
        end
      end

      def add_scope(model, name, parameters)
        relation = "#{parameters} -> ::#{model.name}::ActiveRecord_Relation"

        add_method model, name, relation, singleton: true
        add_method "#{model.name}::GeneratedRelationMethods", name, relation
      end

      # Adds a method unless it's declared elsewhere: inline, in sig/, or already generated.
      # Forced methods are overloads (`| ...`) that extend an existing declaration.
      def add_method(owner, name, types, singleton: false, force: false, key: nil)
        owner_name = owner.is_a?(Module) ? owner.name : owner.to_s

        unless !force && (defined_method?(owner, name, singleton: singleton) || @signatures.method?(owner_name, name, singleton: singleton))
          @generated_methods ||= Set.new
          if @generated_methods.add?([ owner_name, name.to_s, singleton, key ])
            add owner, "def #{"self." if singleton}#{name}: #{types}"
          end
        end
      end

      # Defined inline in the owner or its ancestors (for singleton methods, its singleton class's ancestors)
      def defined_method?(owner, name, singleton:)
        if owner.is_a?(Module)
          (singleton ? [ owner, *owner.singleton_class.ancestors ] : owner.ancestors).any? do |mod|
            @methods.key?(mod) && (@methods[mod].key?([ name.to_sym, singleton ]) || (singleton && mod != owner && @methods[mod].key?([ name.to_sym, false ])))
          end
        end
      end

      # The definition's inline types, with type names made absolute so they resolve in any declaration
      def method_types_of(definition, return_type: nil)
        definition.member.overloads.map do |overload|
          method_type = overload.method_type.map_type { absolute_type(it, definition.nesting) }
          method_type = method_type.update(type: method_type.type.with_return_type(RBS::Parser.parse_type(return_type))) if return_type
          method_type.to_s
        end.join(" | ")
      end

      def absolute_type(type, nesting)
        type.map_type_name { |name, _, _| absolute_type_name(name, nesting) }.then do |mapped|
          mapped.respond_to?(:map_type) ? mapped.map_type { absolute_type(it, nesting) } : mapped
        end
      end

      def absolute_type_name(name, nesting)
        return name if name.absolute?

        nesting.size.downto(0).each do |depth|
          candidate = [ *nesting.first(depth), name.to_s ].join("::")

          if name.class? && (mod = Object.const_get(candidate) rescue nil).is_a?(Module) && mod.name
            return RBS::TypeName.parse("::#{mod.name}")
          elsif @signatures.type_name?(candidate)
            return RBS::TypeName.parse("::#{candidate}")
          end
        end

        name
      end

      def add(owner, member)
        @members[owner.is_a?(Module) ? owner.name : owner.to_s] << member
      end

      # Approximates Ruby's lexical constant lookup from within the given nesting
      def resolve(name, nesting)
        if name.start_with?("::")
          Object.const_get(name.delete_prefix("::"))
        else
          nesting.size.downto(0).each do |depth|
            return Object.const_get([ *nesting.first(depth), name ].join("::"))
          rescue NameError
            next
          end

          raise NameError, "Can't resolve #{name} within #{nesting.join("::")}"
        end
      end

      def namespaces
        undeclared = @declared.flat_map { namespaces_of(it.name) }.uniq - @declared.to_a
        undeclared.sort_by(&:name).map { "#{keyword_for(it.name)} ::#{it.name}\nend" }
      end

      def namespaces_of(name)
        parts = name.split("::")
        (1...parts.size).map { Object.const_get(parts.first(it).join("::")) }
      end

      def members
        @members.sort_by(&:first).map do |owner, members|
          [ "#{keyword_for(owner)} ::#{owner}", *members.uniq.map { "  #{it}" }, "end" ].join("\n")
        end
      end

      # GeneratedRelationMethods exist only in signatures, as modules
      def keyword_for(name)
        Object.const_get(name).is_a?(Class) ? "class" : "module"
      rescue NameError
        "module"
      end
  end
end
